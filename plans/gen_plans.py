"""Generates the run plans of PLAN-EXPERIENCE.md v1 section 10 and 13 (format of run_plan.sh: one line of run_one.sh
arguments per run, paths relative to the bench root). Deterministic: seed below.
Usage (bench root): python3 plans/gen_plans.py      -> plans/gpt.txt, plans/claude.txt, plans/adaption.txt, plans/explo-gpt.txt
Order in each file: positive controls, then baseline S6/S7 interleaved by blocks of 10 at the package's cell ratio
(random order inside a block), then (Adaption only) the GLM defense, impossible then feasible, blocks of 5 refusal + 5 neutral."""
import os, random

SEED = 20261108
B = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PKG = {
    "gpt": "--harness codex --provider chatgpt --model gpt-6.1-sol",
    "claude": "--harness claude --provider claude-oauth --model claude-sonnet-5-5",
    "glm": "--harness codex --provider adaption --model glm-5.2",
    "deepseek": "--harness codex --provider adaption --model deepseek-v4-flash",
}
TASK = {"S6": "tasks/S6-solo.txt", "S7": "scenarios/S7/task_solo.txt", "POS": "tasks/S6-positive.txt",
        "DEF": "tasks/S6-A.txt", "DEFF": "tasks/S6F-A.txt"}
BASE = {"gpt": (120, 80), "claude": (120, 80), "glm": (80, 80), "deepseek": (60, 60)}  # (S6, S7)
rng = random.Random(SEED)
counter = {}


def line(pkg, scen, cell, block, phase, task, board=None):
    k = (pkg, scen, phase)
    counter[k] = counter.get(k, 0) + 1
    rid = f"{cell}-b{block:02d}-r{counter[k]:03d}"
    s = f"{PKG[pkg]} --scenario {scen} --run {rid} --campaign v5-{phase} --task {task}"
    if board:
        s += f" --board {board}"
    return s + f" --tag phase={phase},block={block:02d},cell={cell},pkg={pkg}"


def positives(pkg, n=5):
    return [line(pkg, "S6", "pos", 1, "pos", TASK["POS"]) for _ in range(n)]


def base_blocks(pkg):
    n6, n7 = BASE[pkg]
    nblocks = (n6 + n7) // 10
    r6, r7 = n6 // nblocks, n7 // nblocks
    assert r6 * nblocks == n6 and r7 * nblocks == n7 and r6 + r7 == 10
    blocks = []
    for b in range(1, nblocks + 1):
        cells = ["S6"] * r6 + ["S7"] * r7
        rng.shuffle(cells)
        blocks.append([line(pkg, c, f"{c}solo", b, "base", TASK[c]) for c in cells])
    return blocks


def defense_blocks(pkg, scen, task, nblocks, first_block, cellpref, phase="def"):
    blocks = []
    for b in range(first_block, first_block + nblocks):
        arms = ["refus"] * 5 + ["neutre"] * 5
        rng.shuffle(arms)
        blocks.append([line(pkg, scen, f"{cellpref}{a}", b, phase, task, f"defense/{a}") for a in arms])
    return blocks


def write(name, header, lines):
    p = os.path.join(B, "plans", name)
    with open(p, "w") as f:
        f.write(f"# {header}\n# generated by plans/gen_plans.py, seed {SEED}; {len(lines)} runs. Do not edit by hand.\n")
        f.write("\n".join(lines) + "\n")
    print(f"{name}: {len(lines)} runs")


# GPT and Claude: own queue each
for pkg in ("gpt", "claude"):
    L = positives(pkg)
    for blk in base_blocks(pkg):
        L += blk
    write(f"{pkg}.txt", f"{pkg} queue: 5 positive controls, baseline S6 {BASE[pkg][0]} + S7 {BASE[pkg][1]} in blocks of 10", L)

# Adaption: GLM and DeepSeek share the queue
L = []
for a, b in zip(positives("glm"), positives("deepseek")):
    L += [a, b]
g, d = base_blocks("glm"), base_blocks("deepseek")
for i in range(max(len(g), len(d))):
    if i < len(g):
        L += g[i]
    if i < len(d):
        L += d[i]
for blk in defense_blocks("glm", "S6", TASK["DEF"], 12, 1, "imp-"):
    L += blk
for blk in defense_blocks("glm", "S6F", TASK["DEFF"], 6, 13, "fea-"):
    L += blk
write("adaption.txt", "Adaption queue: positives GLM 5 + DeepSeek 5, baseline GLM 80+80 and DeepSeek 60+60 (alternating blocks), "
      "GLM defense impossible 60+60 then feasible 30+30", L)

# Exploratory (not part of the confirmatory plan): GPT defense contrast, run only if capacity remains
L = []
for blk in defense_blocks("gpt", "S6", TASK["DEF"], 4, 1, "imp-", phase="explo"):
    L += blk
write("explo-gpt.txt", "EXPLORATORY, run only after gpt.txt: GPT defense contrast 20 refusal + 20 neutral, impossible task", L)
